"""Times each caption word to the narrator: Whisper word timestamps, snapped to real speech onsets in the audio.

Writes src/captions.ts. Needs public/vo/words.json (from Whisper, word_timestamps=True).
"""
import json, wave, numpy as np

words = json.load(open("public/vo/words.json"))
# Each caption's lines, split at phrase boundaries; each word names the Whisper word whose timing it takes.
CAPTIONS = {
    "l1": [[("Every", 0), ("day,", 1)], [("you", 2), ("push", 3), ("your", 4), ("limits.", 5)]],
    "l2": [[("Your", 0), ("watch", 1), ("knows", 2)], [("when", 3), ("you've", 4), ("gone", 5), ("too", 6), ("far.", 7)]],
    "l3": [[("Three", 0), ("refactors", 1)], [("before", 2), ("lunch.", 3)]],
    "l4": [[("Personal", 0), ("best.", 1)], [("3.2", 2), ("billion", 4), ("tokens.", 5)]],
    "l5": [[("Recovery", 0), ("is", 1)], [("part", 2), ("of", 3), ("training.", 4)]],
    "l6": [[("Burn", 0), ("load:", 1), ("high.", 2)], [("A", 3), ("47-day", 4), ("streak.", 6)]],
    "l7": [[("Detraining.", 1)]],
}

def onsets(path):
    """Times where speech starts again after at least 60ms below -38dB."""
    w = wave.open(path); sr = w.getframerate(); ch = w.getnchannels()
    x = np.frombuffer(w.readframes(w.getnframes()), dtype=np.int16).astype(float)
    if ch == 2: x = x[::2]
    x /= 32768; hop = int(sr * 0.01)
    db = [20 * np.log10(np.sqrt(np.mean(x[i:i + hop] ** 2)) + 1e-9) for i in range(0, len(x) - hop, hop)]
    out, quiet = [], 6
    for i, v in enumerate(db):
        if v < -38:
            quiet += 1
        else:
            if quiet >= 6: out.append(i / 100)
            quiet = 0
    return out

result = {}
for name, lines in CAPTIONS.items():
    starts, prev, timed = onsets(f"public/vo/{name}.wav"), -1.0, []
    for line in lines:
        row = []
        for text, idx in line:
            _, ws, we = words[name][idx]
            near = [s for s in starts if ws - 0.15 <= s <= we + 0.1 and s > prev + 0.05]
            t = near[0] if near else max(ws, prev + 0.12)
            row.append([text, round(t, 2)]); prev = t
        timed.append(row)
    result[name] = timed
    print(name, " / ".join(" ".join(f"{w}@{t}" for w, t in r) for r in timed))

open("src/captions.ts", "w").write(
    "// Generated by align-captions.py: Whisper word timestamps snapped to speech onsets (seconds into each line).\n"
    "export const CAPTIONS: Record<string, [string, number][][]> = " + json.dumps(result) + ";\n")
